console.log(`  ${OUT}.compass.json   ${compassRows.length} COMPASS rows, profileable`);
console.log(`  ${OUT}.cmdb.json      ${products.length} CMDB records`);
console.log(`  ${OUT}.cms.json       ${cms.products.length} CMS create-requests`);
console.log(`  ${OUT}.manifest.json  planted defects: ${planted.length}, known negatives: ${knownNegatives.length}`);
